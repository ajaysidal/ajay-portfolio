const PYTHON_DOCS_AGENT = `# docs_agent.py - Auto-generate documentation from code comments
import ast
import pathlib
from typing import List, Dict

class DocumentationAgent:
    def __init__(self, repo_path: str):
        self.repo_path = pathlib.Path(repo_path)

    def parse_python_file(self, file_path: pathlib.Path) -> List[Dict]:
        """Extract docstrings and comments from Python source files."""
        with open(file_path, "r") as f:
            source = f.read()

        tree = ast.parse(source)
        documentation = []

        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                docstring = ast.get_docstring(node)
                node_type = "class" if isinstance(node, ast.ClassDef) else "function"
                doc = dict()
                doc["name"] = node.name
                doc["type"] = node_type
                doc["file"] = str(file_path)
                doc["line"] = node.lineno
                doc["docstring"] = docstring or "No documentation"
                documentation.append(doc)

        return documentation

    def generate_markdown(self, docs: List[Dict]) -> str:
        """Generate Markdown documentation from parsed code."""
        lines = ["# Auto-Generated API Documentation", ""]
        lines.append(
            "_Generated by Documentation Agent on "
            + __import__("datetime").datetime.now().isoformat()
            + "_"
        )
        lines.append("")

        for doc in docs:
            lines.append("## " + doc["name"] + " (" + doc["type"] + ")")
            lines.append("**File:** \`" + doc["file"] + "\`")
            lines.append("**Line:** " + str(doc["line"]))
            lines.append("")
            lines.append(doc["docstring"])
            lines.append("")

        return "\\n".join(lines)

    def run(self):
        """Scan repository and generate documentation."""
        all_docs = []
        for py_file in self.repo_path.rglob("*.py"):
            if "__pycache__" not in str(py_file):
                all_docs.extend(self.parse_python_file(py_file))

        markdown = self.generate_markdown(all_docs)
        output_path = self.repo_path / "docs" / "API.md"
        output_path.parent.mkdir(exist_ok=True)
        output_path.write_text(markdown)
        print("Generated documentation for " + str(len(all_docs)) + " symbols")


if __name__ == "__main__":
    agent = DocumentationAgent(repo_path="./src")
    agent.run()`;

